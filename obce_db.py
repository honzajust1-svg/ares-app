def hledej(query: str) -> list[tuple[str, str]]:
    """Fulltext hledani v nazvu obce (case-insensitive)."""
    q = query.lower().strip()
    if not q:
        return OBCE
    return [(n, k) for n, k in OBCE if q in n.lower()]


def kod_pro_obec(nazev: str) -> str | None:
    """Vraci RUIAN kod pro nazev obce (ignoruje cast v zavorkach)."""
    nazev_lower = nazev.lower().strip()
    for n, k in OBCE:
        if n.lower().split(" (")[0] == nazev_lower:
            return k
    return None
